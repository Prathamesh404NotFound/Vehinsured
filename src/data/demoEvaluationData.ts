async function loadImageAsCompressedPreview(url: string): Promise<string> {
  try {
    const res = await fetch(url);
    const blob = await res.blob();
    const compressed = await compressImageForPreview(blob, 700, 700, 0.72);
    return compressed.previewBase64;
  } catch {
    return url;
  }
}

