import test from 'node:test';
import assert from 'node:assert/strict';
import { generateAssessmentPdfReport, exportBundleAsJson } from './reportGenerator';
import { calculateRepairEstimate } from '../cost-estimation/calculator';
import { ClaimAssistanceCase, DamageAssessment, Vehicle } from '../../types';

test('generateAssessmentPdfReport creates a multi-section PDF with non-empty output and handles Unicode safely', () => {
  const vehicle: Vehicle = {
    id: 'v1',
    uid: 'u1',
    registrationNumber: 'MH12RT4821',
    displayRegistrationNumber: 'MH 12 RT 4821',
    make: 'Maruti Suzuki',
    model: 'Swift',
    manufacturingYear: 2022,
    category: 'hatchback',
    ownerRelationship: 'self',
    createdAt: Date.now(),
    updatedAt: Date.now(),
  };

  const assessment: DamageAssessment = {
    id: 'a1',
    claimId: 'c1',
    uid: 'u1',
    inferenceMethod: 'illustrative_demo',
    modelIdentifier: 'Example assessment — illustrative data, not generated by the AI model.',
    status: 'completed',
    regions: [
      {
        id: 'r1',
        partName: 'Front Bumper',
        damageType: 'dent',
        severity: 'moderate',
        isIllustrativeDemo: true,
      },
    ],
    isVehicleDrivableAccordingToUser: true,
    safetyNoticeRequired: false,
    createdAt: Date.now(),
    updatedAt: Date.now(),
  };

  const claim: ClaimAssistanceCase = {
    id: 'c1',
    uid: 'u1',
    caseReference: 'CLAIM-TEST-001',
    vehicleId: 'v1',
    incidentDate: '2026-10-01',
    incidentTime: '15:00',
    location: 'Pune स्टेशन Road',
    description: 'Low speed bumper scrape',
    typeOfIncident: 'single_vehicle',
    otherVehicleInvolved: false,
    isDrivable: true,
    evidenceList: [],
    isDeceasedCase: false,
    status: 'submitted_for_review',
    documentIds: [],
    currentWizardStep: 8,
    createdAt: Date.now(),
    updatedAt: Date.now(),
  };

  const costEstimate = calculateRepairEstimate(assessment.regions, vehicle.category);
  const pdf = generateAssessmentPdfReport({
    claim,
    vehicle,
    assessment,
    costEstimate,
  });

  const arrayBuffer = pdf.output('arraybuffer');
  assert.ok(arrayBuffer.byteLength > 1000, 'PDF output should contain valid bytes');
  assert.ok(pdf.getNumberOfPages() >= 1);

  const json = exportBundleAsJson({ claim, vehicle, assessment, costEstimate });
  assert.ok(json.includes('CLAIM-TEST-001'));
  assert.ok(json.includes('पुणे') || json.includes('स्टेशन'));
});
